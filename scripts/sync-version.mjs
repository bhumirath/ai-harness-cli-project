import { readFileSync, writeFileSync } from 'node:fs'

const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'))
if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/.test(pkg.version)) {
  throw new Error('package.json must have a valid version')
}
const path = new URL('../src/version.ts', import.meta.url)
const expected = `// Generated by scripts/sync-version.mjs from package.json.\nexport const VERSION = '${pkg.version}'\n`
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== expected)
    throw new Error('Version mismatch: run pnpm exec node scripts/sync-version.mjs')
} else writeFileSync(path, expected)
if (process.argv.includes('--tag')) {
  if (process.env.GITHUB_REF_NAME !== `v${pkg.version}`)
    throw new Error('Release tag must match package.json version')
}
